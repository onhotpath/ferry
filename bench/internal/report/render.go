package report

import (
	"fmt"
	"sort"
	"strings"
)

// Input is everything the renderer is given.
type Input struct {
	// Meta is the run's provenance.
	Meta Meta

	// Stats is the parsed benchstat CSV: the only source of a number.
	Stats *Stats

	// Scenarios and Absences are the harness's description of itself.
	Scenarios []ScenarioDoc
	Absences  []AbsenceDoc

	// BenchstatText and RawBench are embedded verbatim as appendices, so that
	// anybody can re-derive every table above them.
	BenchstatText string
	RawBench      string
}

// ferryImpl is the column the "where ferry loses" section is written from.
const ferryImpl = "ferry"

// Results renders the full results file.
func Results(in *Input) string {
	var b strings.Builder

	writeHeading(&b, in)
	writeEnvironment(&b, in)
	writeRules(&b)

	for _, sc := range in.Scenarios {
		writeScenario(&b, in, sc)
	}

	writeChartRef(&b, in, chartBasenames)
	writeGeomean(&b, in)
	writeLosses(&b, in)
	writeAbsences(&b, in)
	writeTagConfound(&b, in)
	writeAppendices(&b, in)

	return b.String()
}

func writeHeading(b *strings.Builder, in *Input) {
	fmt.Fprint(b, "# ferry against the libraries people choose between\n\n")
	fmt.Fprint(b, "<!-- Generated by bench/cmd/perfreport. Do not edit by hand. -->\n\n")
	fmt.Fprint(b, "Every figure below was measured by the harness on the machine named in the next section.\n")
	fmt.Fprint(b, "Nothing here is estimated, extrapolated or carried over from another run.\n")
	fmt.Fprint(b, "A cell reading `"+notMeasured+"` is a measurement that was not taken, and the reason is\n")
	fmt.Fprint(b, "in [what was not measured](#what-was-not-measured).\n\n")
	fmt.Fprintf(b, "Generated %s.\n\n", value(in.Meta.Generated))
}

func writeEnvironment(b *strings.Builder, in *Input) {
	m := &in.Meta

	fmt.Fprint(b, "## The machine, the toolchain and the versions\n\n")
	fmt.Fprint(b, "| | |\n| --- | --- |\n")
	fmt.Fprintf(b, "| runner | %s |\n", value(m.Runner))
	fmt.Fprintf(b, "| GOOS / GOARCH | %s / %s |\n", value(m.GOOS), value(m.GOARCH))
	fmt.Fprintf(b, "| CPUs | %s |\n", value(cpuLine(in)))
	fmt.Fprintf(b, "| Go toolchain | %s |\n", value(m.GoVersion))
	fmt.Fprintf(b, "| ferry revision | %s |\n", value(m.FerryRevision))
	fmt.Fprintf(b, "| harness revision | %s |\n", value(m.HarnessRevision))
	fmt.Fprintf(b, "| -count | %s |\n", value(m.Count))
	fmt.Fprintf(b, "| -benchtime | %s |\n", value(m.Benchtime))
	fmt.Fprint(b, "\nThe command:\n\n```\n"+value(m.Command)+"\n```\n\n")
	writeModules(b, &in.Meta)
}

func writeModules(b *strings.Builder, m *Meta) {
	fmt.Fprint(b, "The competitor versions, read from the harness binary's own build info rather than\n")
	fmt.Fprint(b, "from a go.mod, so these are the versions that were linked:\n\n")
	fmt.Fprint(b, "| module | version |\n| --- | --- |\n")

	paths := make([]string, 0, len(m.Modules))
	for p := range m.Modules {
		paths = append(paths, p)
	}

	sort.Strings(paths)

	for _, p := range paths {
		fmt.Fprintf(b, "| `%s` | %s |\n", p, m.Modules[p])
	}

	if len(paths) == 0 {
		fmt.Fprint(b, "| | not recorded |\n")
	}

	fmt.Fprint(b, "\n")
}

func cpuLine(in *Input) string {
	for _, h := range in.Stats.Header {
		if strings.HasPrefix(h, "cpu:") {
			return strings.TrimSpace(strings.TrimPrefix(h, "cpu:")) +
				fmt.Sprintf(" (GOMAXPROCS %d)", in.Meta.NumCPU)
		}
	}

	return ""
}

func writeRules(b *strings.Builder) {
	fmt.Fprint(b, rulesSection)
}

// rulesSection is the only prose in this file that is not derived from the
// input, and it is the part a reader needs in order to know what the numbers
// are worth.
const rulesSection = `## What is being compared, and the rules

Every library in a scenario loads the **same struct** from the **same source** and has to
produce the **identical** populated value.
That is asserted once, outside every timed loop, against a hand-written expected value that
is spelled independently of both the environment fixture and the YAML document.
If any library produces a different value the harness refuses to run at all, benchmarks
included, so a published table cannot be one where the columns were doing different work.

**cold and warm** are defined by where the constructor is called:

| | |
| --- | --- |
| cold | the loader is constructed on every iteration, then run once |
| warm | the loader is constructed once, then run on every iteration |

So anything a library can amortise across loads sits in the constructor, and the gap
between the two columns is exactly how much there was to amortise.
ferry compiles a schema per type and caches it on a ` + "`Registry`" + `, so cold recompiles it every
time and warm does not.
A library that reflects on every call has nothing to put in the constructor and its two
columns come out the same; that flat line is the finding, not a missing measurement.

**One column in every scenario is the baseline, and it is a floor rather than a competitor.**
It is the same job written out by hand with no mapping layer over it: ` + "`os.Getenv`" + ` plus
` + "`strconv`" + ` for the environment scenarios, a direct ` + "`yaml.Unmarshal`" + ` for the YAML ones.
It is measured, and its raw figure is published in every table below, unrounded.
What it is not is a library. No mapping library can beat the code a mapping library would
otherwise have to generate, so every row here loses to it by construction, and being told
which row lost by the least is not information.
So the baseline is left out of "the fastest other library" and used instead as the
denominator of one multiple, rendered against every library in the comparison and computed
the same way for each, ferry included.
That multiple is what the abstraction costs over the same floor, and it is the figure to
read: it is the one number in this file that compares a library to something no library
gets to move.

**Where the libraries differ semantically, the difference is in the notes** under each
table rather than smoothed over.
Some of those differences are large: ferry's YAML dump edits an existing document and
fsyncs it, while the columns beside it serialise a fresh one and do not.

**The destination is allocated once, outside the timed loop, and reused across iterations.**
Funnelling a fifty-one field struct back through an ` + "`any`" + ` on every iteration would box it,
which is a heap allocation of the whole struct charged identically to every column and large
enough to swamp the differences these tables exist to show.
The equivalence check gets a fresh destination for every library, which is where sharing one
would actually hide a defect.

### What these numbers are worth

A GitHub-hosted runner is a shared virtual machine with a neighbour on it.
Benchmark numbers taken there have wide variance, the confidence intervals below say how
wide, and a difference inside them is not a difference.
The runner this run used is named above; if it is a hosted one, read the ratios and not the
absolute figures, and read a single-digit percentage as noise.
This repository has no self-hosted runner today, and a self-hosted one would be the better
target for this job.

`

func writeScenario(b *strings.Builder, in *Input, sc ScenarioDoc) {
	fmt.Fprintf(b, "## `%s`\n\n%s\n\n", sc.Name, sc.What)
	fmt.Fprint(b, "| library | cold | warm | warm x baseline | warm B/op | warm allocs/op |\n")
	fmt.Fprint(b, "| --- | --- | --- | --- | --- | --- |\n")

	for _, impl := range sc.Impls {
		writeScenarioRow(b, in, sc, impl)
	}

	fmt.Fprint(b, "\n")

	writeCaveats(b, sc)

	for _, impl := range sc.Impls {
		fmt.Fprintf(b, "- **%s**%s %s\n", implLabel(impl), moduleSuffix(impl), impl.Notes)
	}

	fmt.Fprint(b, "\n")
}

func writeScenarioRow(b *strings.Builder, in *Input, sc ScenarioDoc, impl ImplDoc) {
	cold, coldOK := in.Stats.Lookup(Key{Scenario: sc.Name, Mode: "cold", Impl: impl.Name})
	warm, warmOK := in.Stats.Lookup(Key{Scenario: sc.Name, Mode: "warm", Impl: impl.Name})

	fmt.Fprintf(b, "| %s | %s | %s%s | %s%s | %s | %s |\n",
		implLabel(impl),
		measured(cold, coldOK, unitSec),
		measured(warm, warmOK, unitSec), caveatMark(impl),
		baselineCell(in, sc, impl), caveatMark(impl),
		measured(warm, warmOK, unitBytes),
		measured(warm, warmOK, unitAllocs),
	)
}

// implLabel is how a library is named in a table cell. The baseline says what
// it is everywhere it appears, because a row that cannot be beaten reads as a
// row that won unless it is labelled.
func implLabel(impl ImplDoc) string {
	if impl.Baseline {
		return impl.Name + " " + BaselineTag
	}

	return impl.Name
}

// BaselineTag is spelled once, in every table and on the chart.
const BaselineTag = "(baseline)"

// baselineOf is the scenario's baseline measurement: the same job with no
// mapping layer, and the denominator of every multiple this file renders.
//
// A scenario that declares no baseline, or whose baseline was not measured,
// gets no multiple at all rather than one over whichever row happened to be
// quickest.
func baselineOf(in *Input, sc ScenarioDoc) (secs float64, name string, ok bool) {
	for _, impl := range sc.Impls {
		if !impl.Baseline {
			continue
		}

		if got, found := warmSeconds(in, sc.Name, impl.Name); found {
			return got, impl.Name, true
		}
	}

	return 0, "", false
}

// baselineCell renders one library's warm time as a multiple of the baseline's.
//
// It is computed the same way for every row in the table, ferry's included.
// The baseline's own row says what it is rather than reading 1.00x, which would
// look like a measurement rather than a definition.
func baselineCell(in *Input, sc ScenarioDoc, impl ImplDoc) string {
	base, _, ok := baselineOf(in, sc)
	if !ok {
		return notMeasured
	}

	if impl.Baseline {
		return "1.00x, by definition"
	}

	got, found := warmSeconds(in, sc.Name, impl.Name)
	if !found {
		return notMeasured
	}

	return ratio(got, base)
}

// caveatMark is the dagger that goes on the number itself.
//
// A sentence underneath a table is something a reader may not reach before
// quoting the figure above it, so a warm column that is not comparable is
// marked where it is read.
func caveatMark(impl ImplDoc) string {
	if impl.WarmCaveat == "" {
		return ""
	}

	return " " + caveatDagger
}

// caveatDagger is spelled once.
const caveatDagger = "†"

// writeCaveats prints the footnote for every marked cell in one scenario.
func writeCaveats(b *strings.Builder, sc ScenarioDoc) {
	for _, impl := range sc.Impls {
		if impl.WarmCaveat == "" {
			continue
		}

		fmt.Fprintf(b, "%s **%s's warm figure is not comparable with the rest of this table.** %s\n\n",
			caveatDagger, impl.Name, impl.WarmCaveat)
	}
}

func measured(m map[string]Metric, ok bool, unit string) string {
	if !ok {
		return notMeasured
	}

	return cell(m, unit)
}

func moduleSuffix(impl ImplDoc) string {
	if impl.Module == "" {
		return ""
	}

	return " (`" + impl.Module + "`)"
}

// chartBasenames is how the results file refers to the charts: they are
// written into the same directory, so a bare filename is the link.
func chartBasenames(link string) string {
	if i := strings.LastIndex(link, "/"); i >= 0 {
		return link[i+1:]
	}

	return link
}

// writeChartRef points at the two SVGs the same run produced.
//
// A <picture> with a prefers-color-scheme media query is how GitHub markdown
// selects between a light and a dark image, and two files is the reliable way
// to do that: one file with an @media rule inside it depends on the sanitiser
// and the image proxy leaving a <style> element alone.
func writeChartRef(b *strings.Builder, in *Input, name func(string) string) {
	if in.Meta.ChartLightLink == "" || in.Meta.ChartDarkLink == "" {
		return
	}

	fmt.Fprint(b, "## The same numbers, drawn\n\n")
	fmt.Fprint(b, "Generated by the same program, from the same parsed benchstat output as every\n")
	fmt.Fprint(b, "table above, so the chart and the tables cannot disagree.\n\n")
	fmt.Fprintf(b, "<picture>\n  <source media=\"(prefers-color-scheme: dark)\" srcset=\"%s\">\n"+
		"  <img alt=\"%s\" src=\"%s\">\n</picture>\n\n",
		name(in.Meta.ChartDarkLink), chartAlt, name(in.Meta.ChartLightLink))
}

// chartAlt is the image's alternative text, and it says what the chart shows
// rather than that it is a chart.
const chartAlt = "Time and allocations per load for every library in every scenario, cold and warm, " +
	"with benchstat's confidence interval. Time is a log scale; allocations are linear from zero."

// writeGeomean publishes benchstat's geometric mean over every benchmark in
// the run, which is the one number that summarises a whole run and the one it
// is easiest to quote without saying where it came from.
//
// It is over every row, ferry's and every competitor's, so it says nothing
// about who won. It is here because benchstat computed it and dropping a
// figure because it flatters nobody is the same sin as inventing one.
func writeGeomean(b *strings.Builder, in *Input) {
	fmt.Fprint(b, "## benchstat's geometric mean\n\n")
	fmt.Fprint(b, "Over every benchmark in the run, every library and both modes together, so it\n")
	fmt.Fprint(b, "ranks nobody. A unit benchstat declined to compute a mean for - it does that when\n")
	fmt.Fprint(b, "any row is zero - is absent rather than zero.\n\n")
	fmt.Fprint(b, "| unit | geomean |\n| --- | --- |\n")

	for _, unit := range []string{unitSec, unitBytes, unitAllocs} {
		got, ok := in.Stats.Geomean[unit]
		if !ok {
			// Not the same thing as an unmeasured cell, and it would be wrong
			// to say so: the benchmarks ran, and benchstat declined the mean.
			fmt.Fprintf(b, "| %s | benchstat computed none |\n", unit)

			continue
		}

		fmt.Fprintf(b, "| %s | %s |\n", unit, cell(map[string]Metric{unit: got}, unit))
	}

	fmt.Fprint(b, "\n")
}

// writeLosses is the section the owner asked for first, and it is derived from
// the measurements rather than written: for every scenario, every library that
// beat ferry on the warm number, with the ratio.
func writeLosses(b *strings.Builder, in *Input) {
	fmt.Fprint(b, "## Where ferry loses\n\n")
	fmt.Fprint(b, "Derived from the warm `sec/op` column above, not written by hand.\n\n")
	fmt.Fprint(b, "The baseline is in this table, marked, and it stays in it.\n")
	fmt.Fprint(b, "It is a real measurement ferry is really that many times slower than, and the fact that\n")
	fmt.Fprint(b, "nothing in the comparison beats it is a reason to label the row, not to drop it.\n\n")
	fmt.Fprint(b, "| scenario | library | warm | ferry warm | ferry is |\n")
	fmt.Fprint(b, "| --- | --- | --- | --- | --- |\n")

	rows := 0

	for _, sc := range in.Scenarios {
		rows += writeLossRows(b, in, sc)
	}

	if rows == 0 {
		fmt.Fprint(b, "| | | | | no library beat ferry in any scenario |\n")
	}

	fmt.Fprint(b, "\n")
}

func writeLossRows(b *strings.Builder, in *Input, sc ScenarioDoc) int {
	ferry, ok := warmSeconds(in, sc.Name, ferryImpl)
	if !ok {
		return 0
	}

	rows := 0

	for _, impl := range sc.Impls {
		if impl.Name == ferryImpl {
			continue
		}

		other, ok := warmSeconds(in, sc.Name, impl.Name)
		if !ok || other >= ferry {
			continue
		}

		fmt.Fprintf(b, "| `%s` | %s | %s | %s | %s slower |\n",
			sc.Name, implLabel(impl), formatDuration(other), formatDuration(ferry), ratio(ferry, other))

		rows++
	}

	return rows
}

func warmSeconds(in *Input, scenario, impl string) (float64, bool) {
	m, ok := in.Stats.Lookup(Key{Scenario: scenario, Mode: "warm", Impl: impl})
	if !ok {
		return 0, false
	}

	got, ok := m[unitSec]

	return got.Value, ok
}

func writeAbsences(b *strings.Builder, in *Input) {
	fmt.Fprint(b, "## What was not measured\n\n")
	fmt.Fprint(b, "A library missing from a table reads as a library that lost, so every one that is\n")
	fmt.Fprint(b, "absent is named here with the reason.\n\n")
	fmt.Fprint(b, "| library | scenario | why |\n| --- | --- | --- |\n")

	for _, a := range in.Absences {
		fmt.Fprintf(b, "| `%s` | %s | %s |\n", a.Library, a.Scenario, a.Why)
	}

	if len(in.Absences) == 0 {
		fmt.Fprint(b, "| | | every library was measured in every scenario |\n")
	}

	fmt.Fprint(b, "\n")
}

// writeTagConfound publishes the one number that says whether the fixture's
// pooled struct tags were necessary.
func writeTagConfound(b *strings.Builder, in *Input) {
	fmt.Fprint(b, "## The struct-tag confound\n\n")
	fmt.Fprint(b, "`reflect.StructTag.Get` scans the tag string linearly, so a fixture carrying one tag key\n")
	fmt.Fprint(b, "per library would charge that length to every library that reflects on every call and not\n")
	fmt.Fprint(b, "to the one that compiles once.\n")
	fmt.Fprint(b, "The fixture pools the tags by grammar instead. This is what that avoided, per two\n")
	fmt.Fprint(b, "lookups on one field:\n\n")
	fmt.Fprint(b, "| tag | sec/op |\n| --- | --- |\n")

	for _, name := range []string{"pooled", "per_library"} {
		m, ok := in.Stats.Named("StructTagCost/" + name)
		fmt.Fprintf(b, "| %s | %s |\n", name, measured(m, ok, unitSec))
	}

	fmt.Fprint(b, "\n")
}

func writeAppendices(b *strings.Builder, in *Input) {
	fmt.Fprint(b, "## Raw benchstat output\n\n```\n")
	fmt.Fprint(b, strings.TrimRight(in.BenchstatText, "\n"))
	fmt.Fprint(b, "\n```\n\n")
	fmt.Fprint(b, "## Raw `go test -bench` output\n\n")
	fmt.Fprint(b, "Every figure above is derived from this, and from nothing else.\n\n<details>\n")
	fmt.Fprint(b, "<summary>expand</summary>\n\n```\n")
	fmt.Fprint(b, strings.TrimRight(in.RawBench, "\n"))
	fmt.Fprint(b, "\n```\n\n</details>\n")
}

// value renders a Meta field, and says so when it is empty rather than
// leaving a blank cell that reads as a measurement.
func value(s string) string {
	if strings.TrimSpace(s) == "" {
		return "not recorded"
	}

	return s
}
